/**
 * Refreshes src/config/locales.json from DataForSEO's reference endpoints (all FREE, cost = 0):
 * the supported location/language combinations per API family. The server uses the snapshot to
 * refuse unsupported combinations BEFORE a payment is requested.
 *
 * Usage: npx tsx --env-file=.env scripts/update-locales.ts      (uses DATAFORSEO_MODE host)
 */
import { writeFileSync } from "node:fs";
import { DFS_BASE_URL, type DfsMode } from "../src/dataforseo/client.js";

const mode = (process.env.DATAFORSEO_MODE ?? "sandbox") as DfsMode;
const auth = "Basic " + Buffer.from(`${process.env.DATAFORSEO_LOGIN}:${process.env.DATAFORSEO_PASSWORD}`).toString("base64");

async function list(path: string): Promise<Record<string, any>[]> {
  const res = await fetch(DFS_BASE_URL[mode] + path, { headers: { Authorization: auth }, signal: AbortSignal.timeout(60_000) });
  const json = (await res.json()) as any;
  const task = json?.tasks?.[0];
  if (json?.status_code !== 20000 || task?.status_code !== 20000) throw new Error(`${path}: ${json?.status_message}`);
  if (json.cost > 0) throw new Error(`${path}: unexpectedly billed ${json.cost} USD — aborting`);
  return task.result ?? [];
}

const codes = (rows: Record<string, any>[], key: string) => [...new Set(rows.map((r) => r[key]))].sort((a, b) => (a > b ? 1 : -1));
const pairs = (rows: Record<string, any>[]) =>
  Object.fromEntries(rows.map((r) => [String(r.location_code), (r.available_languages as any[]).map((l) => l.language_code).sort()]));

// NOTE: the SANDBOX returns truncated dummy location lists for Google Ads and SERP (only the UK),
// so those are not used. Labs/AI lists and all language lists are complete. Country-level
// location codes are taken from the Labs list (94 countries; all of them exist in Google Ads/SERP).
const [adsLang, serpLang, labs, ai, bingLang, bingLoc, trendsLang, trendsLoc] = await Promise.all([
  list("/v3/keywords_data/google_ads/languages"),
  list("/v3/serp/google/languages"),
  list("/v3/dataforseo_labs/locations_and_languages"),
  list("/v3/ai_optimization/ai_keyword_data/locations_and_languages"),
  list("/v3/serp/bing/languages"),
  list("/v3/serp/bing/locations"),
  list("/v3/keywords_data/google_trends/languages"),
  list("/v3/keywords_data/google_trends/locations"),
]);
const countryCodes = (rows: Record<string, any>[]) => rows.filter((r) => r.location_type === "Country").map((r) => r.location_code as number).sort((a, b) => a - b);

const out = {
  _note: "Generated by scripts/update-locales.ts from DataForSEO reference endpoints. Do not edit by hand.",
  generated_at: new Date().toISOString().slice(0, 10),
  source_mode: mode,
  countries: codes(labs, "location_code"),
  google_ads_languages: codes(adsLang, "language_code"),
  serp_languages: codes(serpLang, "language_code"),
  labs: pairs(labs),
  ai: pairs(ai),
  bing_countries: countryCodes(bingLoc),
  bing_languages: codes(bingLang, "language_code"),
  trends_countries: countryCodes(trendsLoc),
  trends_languages: codes(trendsLang, "language_code"),
};
writeFileSync(new URL("../src/config/locales.json", import.meta.url), JSON.stringify(out) + "\n");

// City/region-level Google locations for DACH (Google SERP family only). Free reference endpoint, checked for cost 0 like above.
const KEEP = new Set(["City", "Municipality", "District", "State", "Canton", "Region"]);
const dachRows = (await Promise.all(["de", "at", "ch"].map((c) => list(`/v3/serp/google/locations/${c}`))))
  .flat()
  .filter((r) => KEEP.has(r.location_type) && ["DE", "AT", "CH"].includes(r.country_iso_code))
  .map((r) => [r.location_code, r.location_name, r.location_type, r.country_iso_code])
  .sort((a, b) => (a[0] as number) - (b[0] as number));
writeFileSync(
  new URL("../src/config/locations-dach.json", import.meta.url),
  JSON.stringify({
    _note: "Generated by scripts/update-locales.ts from DataForSEO /v3/serp/google/locations/{de,at,ch} (free reference endpoint). City/region-level Google locations for DACH. Rows: [location_code, location_name, location_type, country_iso_code].",
    generated_at: new Date().toISOString().slice(0, 10),
    rows: dachRows,
  }) + "\n",
);
console.log(`locations-dach.json: ${dachRows.length} DACH cities/regions`);
console.log(
  `locales.json: ${out.countries.length} countries, ads ${out.google_ads_languages.length} languages, ` +
    `serp ${out.serp_languages.length} languages, labs ${Object.keys(out.labs).length} locations, ai ${Object.keys(out.ai).length} locations`,
);
